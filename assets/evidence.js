import {COLUMNS,CONDITIONS,parseCSV,analyzeDataset,demoRows,toCSV} from '../src/evidence.mjs';
const $=id=>document.getElementById(id);
let source='synthetic_demo',rows=[],report=null;
const format=(num,precision=1)=>Number(num).toLocaleString(undefined,{minimumFractionDigits:precision,maximumFractionDigits:precision});
function makeText(tag,text,cls){
 const el=document.createElement(tag);
 el.textContent=text;
 if(cls)el.className=cls;
 return el;
}
function warning(message){
 $('error-message').hidden=!message;
 $('error-message').textContent=message||'';
}
function setSource(origin){
 source=origin;
 const demo=source==='synthetic_demo';
 $('dataset-source').textContent=demo?'SYNTHETIC DEMO · NOT EVIDENCE':'IMPORTED CSV · UNVERIFIED';
 $('dataset-description').textContent=demo
 ?'All records are generated by an arbitrary formula for UI testing. They are not lab observations.'
 :'The numbers came from a local CSV file. No measurement authenticity or calibration has been verified.';
 $('evidence-status').textContent=demo?'DEMO':'UNVERIFIED';
 $('source-detail').textContent=demo?'Synthetic, no physical results':'User-supplied measurements, unverified';
}
function renderTable(groups){
 const tbody=$('group-body');
 tbody.replaceChildren(...groups.map(g=>{
  const tr=document.createElement('tr');
  for(const val of [
   g.condition+' · '+CONDITIONS[g.condition],String(g.n),
   format(g.removalPercent)+'%',format(g.recoveryPercent)+'%',
   format(g.unaccountedSoilMg)+' mg',format(g.water_ml)+' mL',
   format(g.energy_wh,2)+' Wh',format(g.damage_score,2)
  ])tr.append(makeText('td',val));
  return tr;
 }));
}
function renderComparisons(comparisons){
 $('comparison-cards').replaceChildren(...comparisons.map(c=>{
  const card=makeText('article','','comparison-card'+(c.eligible?'':' blocked'));
  const header=makeText('div','','comparison-top');
  header.append(makeText('strong',c.treat+' vs '+c.control),makeText('span',c.eligible?'DESCRIPTIVE ONLY':'BLOCKED'));
  card.append(header,makeText('p',c.question));
  if(c.comparison){
   const x=c.comparison;
   card.append(makeText('strong',(x.difference>=0?'+':'')+format(x.difference)+' percentage points','difference'));
   card.append(makeText('p','95% exploratory bootstrap interval: ['+format(x.low)+', '+format(x.high)+'] percentage points · n='+c.treatedN+' vs '+c.controlN+'.'));
  }else{
   card.append(makeText('p','n='+c.treatedN+' vs '+c.controlN+'. '+c.reasons.join(' ')));
  }
  return card;
 }));
}
function chart(groups){
 const canvas=$('chart'),ctx=canvas.getContext('2d');
 if(!ctx)return;
 const w=canvas.clientWidth,h=canvas.clientHeight,dpr=Math.min(window.devicePixelRatio||1,2);
 if(canvas.width!==Math.round(w*dpr)||canvas.height!==Math.round(h*dpr)){canvas.width=Math.round(w*dpr);canvas.height=Math.round(h*dpr);}
 ctx.setTransform(dpr,0,0,dpr,0,0);ctx.clearRect(0,0,w,h);
 const left=48,right=w-18,top=22,bottom=h-57;
 const vals=groups.map(g=>g.removalPercent);
 const floor=Math.min(0,...vals),ceiling=Math.max(100,...vals);
 const lower=Math.floor(floor/20)*20,upper=Math.ceil(ceiling/20)*20 || 100;
 function py(value){return bottom-(value-lower)/(upper-lower)*(bottom-top);}
 ctx.font='10px ui-monospace,monospace';ctx.textAlign='right';
 for(let step=0;step<=4;step++){
  const v=lower+(upper-lower)*step/4,y=py(v);
  ctx.fillStyle='#7aa6b1';ctx.fillText(format(v,0)+'%',left-7,y+3);
  ctx.beginPath();ctx.moveTo(left,y);ctx.lineTo(right,y);
  ctx.strokeStyle='rgba(136,190,192,.2)';ctx.lineWidth=1;ctx.stroke();
 }
 const colWidth=(right-left)/(groups.length||1),barWidth=Math.min(52,colWidth*.55);
 ctx.textAlign='center';
 for(let i=0;i<groups.length;i++){
  const g=groups[i],cx=left+(i+.5)*colWidth,val=py(g.removalPercent),base=py(0);
  ctx.fillStyle=g.condition==='D'||g.condition==='E'?'#8de4cf':'#458f9b';
  ctx.fillRect(cx-barWidth/2,Math.min(val,base),barWidth,Math.max(1,Math.abs(base-val)));
  ctx.fillStyle='#b8d5d9';ctx.fillText(g.condition,cx,h-28);
  ctx.fillStyle='#d8f4e7';ctx.fillText(format(g.removalPercent,0)+'%',cx,Math.max(top+10,Math.min(val,base)-10));
 }
}
function render(){
 report=analyzeDataset(rows,{origin:source,seed:369});
 if(!report.ok){
  warning('Dataset validation failed: '+report.errors.slice(0,12).join(' | ')+(report.errors.length>12?' (and more)':''));
  return false;
 }
 warning('');
 $('specimen-count').textContent=String(report.specimenCount);
 $('conditions-count').textContent=String(report.groups.length)+' / 6';
 $('eligible-count').textContent=report.comparisons.filter(x=>x.eligible).length+' / 4';
 renderTable(report.groups);renderComparisons(report.comparisons);
 $('finding-list').replaceChildren(...report.issues.map(x=>makeText('li',x)));
 chart(report.groups);
 return true;
}
function setRows(data,origin){
 const check=analyzeDataset(data,{origin});
 if(!check.ok){
  warning('Import rejected: '+check.errors.slice(0,12).join(' | ')+(check.errors.length>12?' (and more)':''));
  return false;
 }
 rows=data;setSource(origin);render();return true;
}
function save(name,type,content){
 const blob=new Blob([content],{type}),url=URL.createObjectURL(blob),a=document.createElement('a');
 a.href=url;a.download=name;document.body.append(a);a.click();a.remove();
 setTimeout(()=>URL.revokeObjectURL(url),1000);
}
$('load-demo').addEventListener('click',()=>setRows(demoRows(),'synthetic_demo'));
$('download-demo').addEventListener('click',()=>save('phipress-SYNTHETIC-DEMO.csv','text/csv;charset=utf-8',toCSV(demoRows())));
$('csv-template').addEventListener('click',()=>save('phipress-E0-blank-template.csv','text/csv;charset=utf-8',COLUMNS.join(',')+'\n'));
$('upload').addEventListener('change',async()=>{
 const file=$('upload').files?.[0];if(!file)return;
 try{
  if(file.size>2_000_000)throw new Error('File exceeds 2 MB');
  const parsed=parseCSV(await file.text());
  setRows(parsed,'user_supplied_unverified');
 }catch(e){warning('CSV could not be imported: '+e.message);}
 finally{$('upload').value='';}
});
$('export-report').addEventListener('click',()=>{
 if(!report?.ok)return;
 save('phipress-E0-analysis-'+(source==='synthetic_demo'?'SYNTHETIC':'UNVERIFIED')+'.json','application/json',
  JSON.stringify({warning:'NOT A PRODUCT CLAIM OR A VERIFIED MEASUREMENT DATASET',dataset_origin:source,records:rows,analysis:report},null,2));
});
window.addEventListener('resize',()=>{if(report?.ok)chart(report.groups);});
setRows(demoRows(),'synthetic_demo');
